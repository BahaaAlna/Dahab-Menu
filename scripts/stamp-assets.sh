#!/usr/bin/env bash
# ============================================================
#  ختم روابط الأنماط والسكربتات برقم النسخة
#
#  GitHub Pages يُخزّن كل ملف 10 دقائق في المتصفح، فيبقى الهاتف على
#  نسخة قديمة من الأنماط والسكربتات بعد النشر. ختم كل رابط برقم
#  النسخة (?v=...) يجعله رابطاً جديداً عند كل نشر.
#
#  الاستعمال:  bash scripts/stamp-assets.sh <مجلد-الموقع> <رقم-النسخة>
#
#  يُعدَّل مجلد البناء وحده، فمصدر المشروع ومحلّي التطوير لا يتأثّران.
# ============================================================
set -euo pipefail

DIR="${1:?site directory}"
V="${2:?version}"
V="${V:0:8}"

# صفحات HTML: الأنماط وسكربتات الدخول  (assets/css/x.css و assets/js/x.js)
find "$DIR" -maxdepth 1 -name '*.html' -exec \
  sed -i -E "s#((src|href)=\"assets/(css|js)/[^\"?]+\.(css|js))\"#\1?v=$V\"#g" {} +

# وحدات JS: الاستيراد النسبي  (from "./x.js")
find "$DIR/assets/js" -name '*.js' -exec \
  sed -i -E "s#(from \"\./[^\"?]+\.js)\"#\1?v=$V\"#g" {} +

echo "stamped assets with v=$V"
