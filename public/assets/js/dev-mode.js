/* ============================================================
   🧪  وضع التطوير المحلي

   مصدر واحد للإجابة عن سؤال: هل نحن على جهاز التطوير أم على
   الموقع المنشور؟ تعتمد عليه مفاتيح الميزات وحساب الزبون، فلا
   يُكرَّر الفحص في أكثر من ملف ولا تختلف النتيجة بين ملف وآخر.

   تجاوز مؤقّت: إضافة ‎?live=1‎ إلى العنوان تُلغي وضع التطوير،
   فيتعامل الجهاز المحلي مع Firebase الحقيقي. وهي الطريقة التي
   يُتحقَّق بها من الحفظ على الخادم فعلاً قبل النشر.
   ============================================================ */

/** العناوين التي تُعدّ جهاز تطوير. السلسلة الفارغة تغطي file:// */
const LOCAL_HOSTS = ["localhost", "127.0.0.1", "[::1]", ""];

const onLocalHost =
  LOCAL_HOSTS.includes(location.hostname) ||
  location.hostname.endsWith(".localhost");

/** ‎?live=1‎ تعني: اضرب الخادم الحقيقي ولو كنّا محليّاً */
const forcedLive = new URLSearchParams(location.search).get("live") === "1";

export const IS_LOCAL = onLocalHost && !forcedLive;

/** تُضاف إلى روابط التنقّل الداخلية كي لا يضيع وضع ‎?live=1‎
 *  عند الانتقال من صفحة إلى أخرى. */
export const LINK_SUFFIX = forcedLive ? "?live=1" : "";
